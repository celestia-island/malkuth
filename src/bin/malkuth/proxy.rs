/// The rendered 503 page. Assembled once: the substitution is pure and the
/// proxy hot path must not pay for it per connection.
static MAINTENANCE_BODY: LazyLock<String> = LazyLock::new(|| {
    MAINTENANCE_BODY_TEMPLATE
        .replace("/*__TOKENS__*/", MAINTENANCE_TOKENS_CSS)
        .replace("/*__SPINNER__*/", MAINTENANCE_SPINNER_CSS)
});

/// fnv-1a 64-bit.
fn hash64(s: impl AsRef<str>) -> u64 {
    let mut h: u64 = 0xcbf2_9ce4_8422_2325;
    for &b in s.as_ref().as_bytes() {
        h ^= b as u64;
        h = h.wrapping_mul(0x100_0000_01b3);
    }
    h
}

