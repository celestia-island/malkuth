// Build-time asset embedding for malkuth's two rendered surfaces.
//
// 1. The landing/info SPA (`packages/landing_page`, Vue + hikari) is built by
//    `pnpm build` and inlined into a single `index.html`; the whole file is
//    embedded as `LANDING_PAGE_HTML`.
// 2. The SAME component tree is server-rendered at build time into
//    `fallback.html`, a no-JS page whose per-request values are
//    `{{MALKUTH_*}}` markers (src/info_page.rs substitutes them). That file is
//    the fallback served when the SPA was never built, replacing the former
//    hand-written Tera template.
// 3. `hikari-tokens.json` carries the exact CSS custom-property maps the SPA
//    applies at runtime plus the compiled spinner rules; it becomes the Rust
//    constants the 503 restart page renders with, so that page cannot drift
//    from the hikari theme the app uses.
//
// Failure policy (deliberately explicit — the old shape had three silent
// failure modes):
//   * pnpm present but the build fails  -> abort (a failed vite run could
//     still leave a stale artifact dir behind);
//   * pnpm absent                       -> fall back to the committed
//     artifacts under src/info_page/ (generated by `just gen-pages`);
//   * a stale `target/landing_page` without a build stamp is NEVER trusted.
use std::path::{Path, PathBuf};
use std::process::Command;

/// Artifacts build.rs embeds. `target/` copies are produced by
/// `packages/landing_page/scripts/build.mjs`; the committed copies under
/// `src/info_page/` keep no-node builds (CI) working.
const SPA_HTML: &str = "index.html";
const FALLBACK_HTML: &str = "fallback.html";
const TOKENS_JSON: &str = "hikari-tokens.json";
const STAMP: &str = "build-stamp.json";

/// Markers `src/info_page.rs` substitutes in the prerendered fallback page.
/// Pinned here so a renamed/forgotten marker fails the build instead of
/// silently reaching a browser as literal `{{MALKUTH_...}}` text.
const FALLBACK_MARKERS: &[&str] = &[
    "MALKUTH_LANG",
    "MALKUTH_DIR",
    "MALKUTH_TITLE",
    "MALKUTH_AUTO_REFRESH",
    "MALKUTH_LOGO_SRC",
    "MALKUTH_HEADING",
    "MALKUTH_TAGLINE",
    "MALKUTH_STATUS_BADGE",
    "MALKUTH_TASK_ROW",
    "MALKUTH_PROXY_ROW",
    "MALKUTH_WATCH_ROW",
    "MALKUTH_BINARIES_BLOCK",
    "MALKUTH_RETRY_BLOCK",
    "MALKUTH_ACTION_BLOCK",
    "MALKUTH_FOOTER",
    "MALKUTH_VERSION_LINE",
];

fn main() {
    let out_dir = PathBuf::from(std::env::var("OUT_DIR").expect("OUT_DIR"));
    let landing = Path::new("packages/landing_page");
    let dist = Path::new("target/landing_page");
    let committed = Path::new("src/info_page");

    println!("cargo:rerun-if-changed=packages/landing_page/src");
    println!("cargo:rerun-if-changed=packages/landing_page/scripts");
    for extra in [
        "index.html",
        "package.json",
        "vite.config.ts",
        "vite.ssr.config.ts",
        "tsconfig.json",
        "pnpm-lock.yaml",
    ] {
        println!("cargo:rerun-if-changed=packages/landing_page/{extra}");
    }
    println!("cargo:rerun-if-changed=src/info_page/fallback_page.html");
    println!("cargo:rerun-if-changed=src/info_page/design_tokens.json");

    let mut built_now = false;
    if landing.join("package.json").exists() {
        built_now = build_landing_page(landing);
    }

    // Only a stamped artifact directory is trusted; a half-written one would
    // otherwise be embedded silently.
    let dist_trusted = dist.join(STAMP).exists();
    if built_now && !dist_trusted {
        panic!(
            "landing_page build reported success but {}/{} is missing — refusing to embed \
             unstamped artifacts",
            dist.display(),
            STAMP
        );
    }

    // Freshness guard: a failed rebuild must never silently embed a dist older
    // than the landing-page sources (hosts without pnpm that never touched the
    // sources still embed their fresh dist).
    if dist_trusted {
        let dist_mtime = std::fs::metadata(dist.join(SPA_HTML))
            .and_then(|m| m.modified())
            .ok();
        let youngest_src = youngest_mtime(&landing.join("src"));
        if let (Some(dist_mtime), Some(youngest_src)) = (dist_mtime, youngest_src) {
            if dist_mtime < youngest_src {
                panic!(
                    "landing_page artifacts are STALE (older than packages/landing_page/src) \
                     and the rebuild did not succeed — refusing to embed a build that lags the \
                     sources (run `cd packages/landing_page && pnpm install && pnpm build`)"
                );
            }
        }
    }

    // ── SPA: target/ only (there is no committed copy; ~1 MB of inlined JS) ──
    let spa = if dist_trusted {
        read_required(&dist.join(SPA_HTML))
    } else {
        // Historical sentinel: `src/info_page.rs` treats this exact prefix as
        // "SPA not built" and serves the prerendered fallback page instead.
        "<html><body><h1>Malkuth</h1><p>Landing page not built.</p></body></html>".to_string()
    };

    // ── Fallback page: target/ first, committed copy second ──────────────────
    let fallback_path = if dist_trusted && dist.join(FALLBACK_HTML).exists() {
        dist.join(FALLBACK_HTML)
    } else {
        committed.join("fallback_page.html")
    };
    if !fallback_path.exists() {
        panic!(
            "no prerendered fallback page at {} — run `just gen-pages` in the malkuth repo \
             and commit src/info_page/fallback_page.html",
            fallback_path.display()
        );
    }
    let fallback = std::fs::read_to_string(&fallback_path)
        .unwrap_or_else(|e| panic!("cannot read {}: {e}", fallback_path.display()));
    check_markers(&fallback, &fallback_path);

    // ── Theme snapshot: same two sources ────────────────────────────────────
    let tokens_path = if dist_trusted && dist.join(TOKENS_JSON).exists() {
        dist.join(TOKENS_JSON)
    } else {
        committed.join("design_tokens.json")
    };
    if !tokens_path.exists() {
        panic!(
            "no hikari token snapshot at {} — run `just gen-pages` in the malkuth repo and \
             commit src/info_page/design_tokens.json",
            tokens_path.display()
        );
    }
    let tokens_src = std::fs::read_to_string(&tokens_path)
        .unwrap_or_else(|e| panic!("cannot read {}: {e}", tokens_path.display()));
    let tokens: serde_json::Value = serde_json::from_str(&tokens_src)
        .unwrap_or_else(|e| panic!("invalid JSON in {}: {e}", tokens_path.display()));

    println!(
        "cargo:warning=malkuth pages: {} ({} B), {} ({} B), {} ({} B)",
        spa_source(dist, dist_trusted),
        spa.len(),
        fallback_path.display(),
        fallback.len(),
        tokens_path.display(),
        tokens_src.len()
    );

    write_const(
        &out_dir.join("landing_page_html.rs"),
        "LANDING_PAGE_HTML",
        &spa,
    );
    write_const(
        &out_dir.join("fallback_page_html.rs"),
        "FALLBACK_PAGE_HTML",
        &fallback,
    );
    write_tokens(
        &out_dir.join("design_tokens.rs"),
        &tokens,
        &tokens_path,
        dist_trusted,
    );
}

fn spa_source(dist: &Path, trusted: bool) -> String {
    if trusted {
        dist.join(SPA_HTML).display().to_string()
    } else {
        "<built-in sentinel>".to_string()
    }
}

fn read_required(path: &Path) -> String {
    std::fs::read_to_string(path)
        .unwrap_or_else(|e| panic!("cannot read required page artifact {}: {e}", path.display()))
}

/// Build the SPA + prerender + token snapshot.
///
/// Returns `true` when a pnpm binary existed (so the caller can insist on a
/// stamp); a missing pnpm is not an error — hosts without node embed the
/// committed artifacts instead.
fn build_landing_page(landing: &Path) -> bool {
    let pnpm = std::env::var("PNPM_HOME")
        .map(|home| format!("{home}/pnpm"))
        .unwrap_or_else(|_| "pnpm".into());
    let candidates = [
        format!(
            "{}/.nvm/versions/node/v24.18.0/bin/pnpm",
            std::env::var("HOME").unwrap_or_default()
        ),
        pnpm,
    ];
    let mut attempted = false;
    for pnpm_path in &candidates {
        let status = Command::new(pnpm_path)
            .args(["build"])
            .current_dir(landing)
            .status();
        if let Ok(s) = status {
            attempted = true;
            if s.success() {
                println!("cargo:warning=landing_page built successfully with {pnpm_path}");
                return true;
            }
        }
    }
    if attempted {
        panic!(
            "landing_page build was attempted and FAILED — refusing to embed a possibly stale \
             artifact directory (run `cd packages/landing_page && pnpm install && pnpm build` \
             to see the error)"
        );
    }
    println!(
        "cargo:warning=landing_page build skipped (no pnpm on this host) — using committed \
         artifacts from src/info_page/"
    );
    false
}

/// Every marker must appear exactly once, and nothing else may look like one.
fn check_markers(html: &str, path: &Path) {
    let mut seen: Vec<(&str, usize)> = FALLBACK_MARKERS
        .iter()
        .map(|marker| (*marker, html.matches(&format!("{{{{{marker}}}}}")).count()))
        .collect();
    seen.retain(|(_, count)| *count != 1);
    if !seen.is_empty() {
        let detail: Vec<String> = seen
            .iter()
            .map(|(marker, count)| format!("{{{{{marker}}}}}×{count}"))
            .collect();
        panic!(
            "prerendered fallback page {} must contain every marker exactly once; \
             wrong counts: {}",
            path.display(),
            detail.join(", ")
        );
    }
    for (idx, _) in html.match_indices("{{MALKUTH_") {
        let rest = &html[idx + "{{MALKUTH_".len()..];
        let end = match rest.find("}}") {
            Some(end) => end,
            None => continue,
        };
        let name = format!("MALKUTH_{}", &rest[..end]);
        if !FALLBACK_MARKERS.contains(&name.as_str()) {
            panic!(
                "unknown marker {{{{{name}}}}} in {} — update FALLBACK_MARKERS in \
                 build.rs and the renderer in src/info_page.rs together",
                path.display()
            );
        }
    }
}

fn write_const(path: &Path, name: &str, value: &str) {
    let escaped = rust_literal(value);
    std::fs::write(
        path,
        format!(
            "// @generated by build.rs — do not edit\npub const {name}: &str = \"{escaped}\";\n"
        ),
    )
    .unwrap_or_else(|e| panic!("cannot write {}: {e}", path.display()));
}

fn write_tokens(path: &Path, tokens: &serde_json::Value, source: &Path, dist_trusted: bool) {
    let version = tokens
        .get("hikari_version")
        .and_then(|v| v.as_str())
        .unwrap_or("unknown");
    let tokens_css = tokens
        .get("tokens_css")
        .and_then(|v| v.as_str())
        .unwrap_or_else(|| panic!("{} lacks `tokens_css`", source.display()));
    let spinner_css = tokens
        .get("spinner_css")
        .and_then(|v| v.as_str())
        .unwrap_or_else(|| panic!("{} lacks `spinner_css`", source.display()));

    // The snapshot doubles as the contract the tests pin; only the two CSS
    // blobs are referenced from the proxy's hot path, so silence dead_code
    // for the tables instead of hiding the rest of the file from lints.
    let mut out = String::from("// @generated by build.rs — do not edit\n");
    let allow = "#[allow(dead_code)] // pinned by the 503-page contract tests\n";
    out.push_str(allow);
    out.push_str(&format!(
        "pub const DESIGN_TOKENS_SOURCE: &str = \"{}\";\n",
        rust_literal(if dist_trusted {
            "target/landing_page/hikari-tokens.json"
        } else {
            "src/info_page/design_tokens.json"
        })
    ));
    out.push_str(allow);
    out.push_str(&format!(
        "pub const DESIGN_TOKENS_HIKARI_VERSION: &str = \"{}\";\n",
        rust_literal(version)
    ));

    for (scheme, const_name) in [
        ("dark", "DESIGN_TOKENS_DARK"),
        ("light", "DESIGN_TOKENS_LIGHT"),
    ] {
        let map = tokens
            .get(scheme)
            .and_then(|v| v.as_object())
            .unwrap_or_else(|| panic!("{} lacks `{}` token map", source.display(), scheme));
        if map.is_empty() {
            panic!("{} has an empty `{}` token map", source.display(), scheme);
        }
        out.push_str(allow);
        out.push_str(&format!("pub const {const_name}: &[(&str, &str)] = &[\n"));
        for (name, value) in map {
            let value = value
                .as_str()
                .unwrap_or_else(|| panic!("token {name} in {scheme} is not a string"));
            out.push_str(&format!(
                "    (\"{}\", \"{}\"),\n",
                rust_literal(name),
                rust_literal(value)
            ));
        }
        out.push_str("];\n");
    }

    out.push_str(&format!(
        "/// Ready-to-inline CSS custom properties for the 503 restart page.\n\
         pub const MAINTENANCE_TOKENS_CSS: &str = \"{}\";\n",
        rust_literal(tokens_css)
    ));
    out.push_str(&format!(
        "/// Compiled hikari spinner rules (extracted from the shipped stylesheet).\n\
         pub const MAINTENANCE_SPINNER_CSS: &str = \"{}\";\n",
        rust_literal(spinner_css)
    ));
    std::fs::write(path, out).unwrap_or_else(|e| panic!("cannot write {}: {e}", path.display()));
}

/// Escape a string into a Rust string literal body.
fn rust_literal(value: &str) -> String {
    let mut out = String::with_capacity(value.len() + 16);
    for ch in value.chars() {
        match ch {
            '\\' => out.push_str("\\\\"),
            '"' => out.push_str("\\\""),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            c if (c as u32) < 0x20 || (c as u32) > 0x7e => {
                out.push_str(&format!("\\u{{{:x}}}", c as u32))
            }
            c => out.push(c),
        }
    }
    out
}

/// Newest mtime under `dir` (stack-based; unreadable entries are skipped).
fn youngest_mtime(dir: &Path) -> Option<std::time::SystemTime> {
    let mut newest: Option<std::time::SystemTime> = None;
    let mut stack = vec![dir.to_path_buf()];
    while let Some(path) = stack.pop() {
        let entries = match std::fs::read_dir(&path) {
            Ok(entries) => entries,
            Err(_) => continue,
        };
        for entry in entries.flatten() {
            let path = entry.path();
            if path.is_dir() {
                stack.push(path);
            } else if let Ok(modified) = entry.metadata().and_then(|m| m.modified()) {
                newest = Some(match newest {
                    Some(current) if current >= modified => current,
                    _ => modified,
                });
            }
        }
    }
    newest
}
